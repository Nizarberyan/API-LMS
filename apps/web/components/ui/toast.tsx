import { toast, ToastOptions } from "react-toastify";

// Custom toast functions with default styles
export const showSuccess = (message: string, options?: ToastOptions) => {
  toast.success(message, {
    position: "top-right",
    autoClose: 3000,
    hideProgressBar: false,
    closeOnClick: true,
    pauseOnHover: true,
    draggable: true,
    progress: undefined,
    theme: "dark",
    ...options,
  });
};

